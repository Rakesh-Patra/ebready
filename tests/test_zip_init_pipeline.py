"""Exercise the full ZIP init command, including source Scout and its gate."""
import zipfile
from pathlib import Path
from unittest.mock import MagicMock, patch
import pytest
from click.testing import CliRunner
from ebkit.commands.init import init_command
from ebkit.generator.renderer import DeploymentKitRenderer
from ebkit.validator.docker_validator import ScoutResult
from tests.test_interactive_cli import _create_sample_config

@pytest.mark.parametrize('provider',['gordon','unavailable','failed','invalid'])
@pytest.mark.parametrize('gate_passed',[True,False])
def test_zip_init_generation_order_source_scout_and_security_gate(tmp_path,provider,gate_passed):
    source=tmp_path/'project.zip'
    with zipfile.ZipFile(source,'w') as archive:
        archive.writestr('project/requirements.txt','fastapi\nuvicorn\n')
        archive.writestr('project/app/main.py','from fastapi import FastAPI\napp=FastAPI()\n')
    events=[];config=_create_sample_config()
    dockerfile=DeploymentKitRenderer().render(config).files['Dockerfile']
    analyzer=MagicMock()
    def analyze(_scan):events.append('metadata');return config
    analyzer.analyze.side_effect=analyze
    def gordon(*_args,**_kwargs):
        events.append('gordon')
        if provider=='failed':raise RuntimeError('Gordon failed')
        return 'invalid draft' if provider=='invalid' else f'```dockerfile\n{dockerfile}\n```'
    def gemini(*_args,**_kwargs):events.append('gemini');return dockerfile,'Generated by Gemini'
    def scout(project):
        events.append('scout')
        assert Path(project).resolve()==(tmp_path/'project-ebkit').resolve()
        assert (Path(project)/'Dockerfile').read_text(encoding='utf-8').strip()==dockerfile.strip()
        return ScoutResult(gate_passed=gate_passed,critical_count=0 if gate_passed else 1,high_count=0 if gate_passed else 7,summary='Source dependency findings',gate_reason=None if gate_passed else 'Critical CVEs (1) exceed threshold (0).',artifact_kind='source',details=[])
    with patch('ebkit.commands.init.load_config',return_value=None),patch('ebkit.commands.init._check_gemini_key'),patch('ebkit.commands.init.get_analyzer',return_value=analyzer),patch('ebkit.generator.docker_ai.DockerAIService.is_available',return_value=provider!='unavailable'),patch('ebkit.generator.docker_ai.DockerAIService.ask_gordon',side_effect=gordon),patch('ebkit.generator.docker_ai.DockerAIService._generate_multitier_with_gemini',side_effect=gemini),patch('ebkit.validator.docker_validator.DockerScoutValidator.is_scout_available',return_value=True),patch('ebkit.validator.docker_validator.DockerScoutValidator.scan_source',side_effect=scout) as scan_source,patch('ebkit.validator.docker_validator.DockerBuildValidator.build') as build,patch('ebkit.validator.docker_validator.DockerRuntimeValidator.validate') as runtime:
        result=CliRunner().invoke(init_command,['--zip',str(source),'--yes','--no-build','--no-runtime'])
    assert events==(['metadata','gordon','scout'] if provider=='gordon' else ['metadata','gemini','scout'] if provider=='unavailable' else ['metadata','gordon','gemini','scout']),result.output
    scan_source.assert_called_once();build.assert_not_called();runtime.assert_not_called()
    assert 'source dependencies (no image build)' in result.output
    assert (tmp_path/'project-prepared.zip').is_file()
    if gate_passed:
        assert result.exit_code==0,result.output
        assert 'Source dependency security gate passed' in result.output
    else:
        assert result.exit_code!=0,result.output
        assert 'PROJECT NOT READY' in result.output
        assert '--no-scout' in result.output
        assert 'does not fix the reported CVEs' in result.output

def test_zip_init_explicit_scout_bypass_still_warns_and_does_not_scan(tmp_path):
    source=tmp_path/'project.zip'
    with zipfile.ZipFile(source,'w') as archive:
        archive.writestr('requirements.txt','fastapi\nuvicorn\n')
        archive.writestr('app/main.py','from fastapi import FastAPI\napp=FastAPI()\n')
    config=_create_sample_config();analyzer=MagicMock();analyzer.analyze.return_value=config
    dockerfile=DeploymentKitRenderer().render(config).files['Dockerfile']
    with patch('ebkit.commands.init.load_config',return_value=None),patch('ebkit.commands.init._check_gemini_key'),patch('ebkit.commands.init.get_analyzer',return_value=analyzer),patch('ebkit.generator.docker_ai.DockerAIService.generate_dockerfile',return_value=(dockerfile,'Generated by Gordon')),patch('ebkit.generator.docker_ai.DockerAIService.is_available',return_value=True),patch('ebkit.validator.docker_validator.DockerScoutValidator.scan_source') as scout:
        result=CliRunner().invoke(init_command,['--zip',str(source),'--yes','--no-build','--no-runtime','--no-scout'])
    assert result.exit_code==0,result.output
    assert 'SECURITY VALIDATION SKIPPED' in result.output
    assert 'Security readiness is NOT VERIFIED' in result.output
    scout.assert_not_called()
