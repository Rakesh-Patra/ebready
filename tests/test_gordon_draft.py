from unittest.mock import patch
from ebkit.generator.gordon_draft import generate
from ebkit.generator.docker_ai import DockerAIService
from ebkit.analyzer.scanner import ScanResult
from tests.test_interactive_cli import _create_sample_config

def test_unavailable_gordon_returns_no_draft_and_does_not_ask():
    with patch('ebkit.generator.gordon_draft.DockerAIService') as service:
        service.return_value.is_available.return_value=False
        assert generate('project metadata')=={'available':False,'dockerfile':None}
        service.return_value.ask_gordon.assert_not_called()

def test_gordon_reuses_existing_text_only_integration_without_project_directory():
    with patch('ebkit.generator.gordon_draft.DockerAIService') as service:
        instance=service.return_value;instance.is_available.return_value=True
        instance.ask_gordon.return_value='```dockerfile\nFROM node:22-alpine\nCMD ["node","app.js"]\n```'
        instance.extract_dockerfile.return_value='FROM node:22-alpine\nCMD ["node","app.js"]'
        result=generate('metadata and manifests; no tools')
        assert result['available'] and result['dockerfile'].startswith('FROM')
        instance.ask_gordon.assert_called_once_with('metadata and manifests; no tools',timeout=60)

def test_failed_gordon_returns_no_draft_for_gemini_fallback():
    with patch('ebkit.generator.gordon_draft.DockerAIService') as service:
        instance=service.return_value;instance.is_available.return_value=True
        instance.ask_gordon.side_effect=RuntimeError('failed')
        assert generate('project metadata')=={'available':True,'dockerfile':None}

def test_cli_single_tier_also_falls_back_to_gemini_when_gordon_is_unavailable():
    service=DockerAIService();config=_create_sample_config();scan=ScanResult(language='python')
    with patch.object(service,'is_available',return_value=False),patch.object(service,'_generate_multitier_with_gemini',return_value=('FROM python:3.12-slim\nCMD ["python","app.py"]','Generated by Gemini')) as gemini:
        dockerfile,message=service.generate_dockerfile(config,scan)
        assert dockerfile and message=='Generated by Gemini'
        gemini.assert_called_once_with(config,scan,None)

def test_cli_single_tier_falls_back_to_gemini_after_gordon_fails():
    service=DockerAIService();config=_create_sample_config();scan=ScanResult(language='python')
    with patch.object(service,'is_available',return_value=True),patch.object(service,'ask_gordon',side_effect=RuntimeError('failed')),patch.object(service,'_generate_multitier_with_gemini',return_value=('FROM python:3.12-slim\nCMD ["python","app.py"]','Generated by Gemini')) as gemini:
        dockerfile,message=service.generate_dockerfile(config,scan)
        assert dockerfile and message=='Generated by Gemini'
        gemini.assert_called_once()
